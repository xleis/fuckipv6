//! Directional HMAC-SHA-256 key confirmation for the v2 classic profile.
//!
//! Key confirmation proves that both endpoints completed the same handshake and
//! key schedule before either side activates a data epoch. The Initiator and
//! Responder use independent keys, so reflecting a valid tag back under the
//! opposite role fails closed. Tags authenticate the transcript hash with a
//! fixed 256-bit length and are compared in constant time.

use crate::key_schedule::{SessionKeys, SESSION_KEY_LEN};
use crate::transcript::TranscriptHash;
use hmac::{Hmac, Mac};
use sha2::Sha256;
use thiserror::Error;

/// Encoded HMAC-SHA-256 confirmation length.
pub const CONFIRMATION_LEN: usize = 32;

type HmacSha256 = Hmac<Sha256>;

/// The endpoint role that owns a confirmation key and tag.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConfirmationRole {
    /// Confirmation generated by the Initiator.
    Initiator,
    /// Confirmation generated by the Responder.
    Responder,
}

/// A 256-bit key-confirmation tag.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct ConfirmationTag([u8; CONFIRMATION_LEN]);

impl ConfirmationTag {
    /// Parse an exact 32-byte confirmation tag.
    pub fn from_slice(bytes: &[u8]) -> Result<Self, ConfirmationError> {
        if bytes.len() != CONFIRMATION_LEN {
            return Err(ConfirmationError::InvalidLength {
                expected: CONFIRMATION_LEN,
                actual: bytes.len(),
            });
        }
        let mut tag = [0u8; CONFIRMATION_LEN];
        tag.copy_from_slice(bytes);
        Ok(Self(tag))
    }

    /// Borrow the encoded tag.
    pub const fn as_bytes(&self) -> &[u8; CONFIRMATION_LEN] {
        &self.0
    }
}

impl std::fmt::Debug for ConfirmationTag {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("ConfirmationTag(<redacted>)")
    }
}

/// Compute the confirmation tag owned by `role`.
pub fn compute_confirmation(
    keys: &SessionKeys,
    role: ConfirmationRole,
    transcript_hash: &TranscriptHash,
) -> ConfirmationTag {
    compute_with_key(confirmation_key(keys, role), transcript_hash)
}

fn compute_with_key(
    key: &[u8; SESSION_KEY_LEN],
    transcript_hash: &TranscriptHash,
) -> ConfirmationTag {
    let mut mac = HmacSha256::new_from_slice(key).expect("HMAC-SHA-256 accepts keys of any length");
    mac.update(transcript_hash);
    let mut tag = [0u8; CONFIRMATION_LEN];
    tag.copy_from_slice(&mac.finalize().into_bytes());
    ConfirmationTag(tag)
}

/// Verify a confirmation tag for the expected endpoint role.
///
/// The tag must be exactly 32 bytes. Role mismatch, a different transcript, a
/// different key schedule, or any bit mutation returns an error. HMAC
/// verification is delegated to the constant-time `Mac::verify_slice` path.
pub fn verify_confirmation(
    keys: &SessionKeys,
    role: ConfirmationRole,
    transcript_hash: &TranscriptHash,
    received: &[u8],
) -> Result<(), ConfirmationError> {
    if received.len() != CONFIRMATION_LEN {
        return Err(ConfirmationError::InvalidLength {
            expected: CONFIRMATION_LEN,
            actual: received.len(),
        });
    }

    let key = confirmation_key(keys, role);
    let mut mac = HmacSha256::new_from_slice(key).expect("HMAC-SHA-256 accepts keys of any length");
    mac.update(transcript_hash);
    mac.verify_slice(received)
        .map_err(|_| ConfirmationError::Mismatch)
}

fn confirmation_key(keys: &SessionKeys, role: ConfirmationRole) -> &[u8; SESSION_KEY_LEN] {
    match role {
        ConfirmationRole::Initiator => keys.initiator_confirmation_key(),
        ConfirmationRole::Responder => keys.responder_confirmation_key(),
    }
}

/// Errors produced while validating a key-confirmation tag.
#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum ConfirmationError {
    /// The received tag was truncated, oversized, or otherwise not 32 bytes.
    #[error("confirmation must be {expected} bytes, received {actual}")]
    InvalidLength { expected: usize, actual: usize },
    /// The tag did not authenticate under the expected role key and transcript.
    #[error("confirmation mismatch")]
    Mismatch,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::handshake::{ClassicInitiator, ClassicResponder, Ed25519Identity};
    use crate::key_schedule::{derive_session_keys, DerivedSession};
    use crate::transcript::{
        ENDPOINT_CONTEXT_HASH_LEN, SUITE_CHACHA20_POLY1305, TRANSCRIPT_HASH_LEN,
    };

    const NOW: u64 = 1_700_000_000;
    const ENDPOINT: [u8; ENDPOINT_CONTEXT_HASH_LEN] = [0x5a; ENDPOINT_CONTEXT_HASH_LEN];
    const EPOCH: u16 = 7;
    const FIXED_KEY: [u8; SESSION_KEY_LEN] = [0x33; SESSION_KEY_LEN];
    const FIXED_TRANSCRIPT: TranscriptHash = [0x66; TRANSCRIPT_HASH_LEN];

    fn established_session(
        initiator_seed: u8,
        responder_seed: u8,
    ) -> (DerivedSession, DerivedSession) {
        let initiator_identity = Ed25519Identity::from_seed([initiator_seed; 32]);
        let responder_identity = Ed25519Identity::from_seed([responder_seed; 32]);
        let initiator = ClassicInitiator::start(
            &initiator_identity,
            responder_identity.verifying_key(),
            SUITE_CHACHA20_POLY1305,
            ENDPOINT,
            EPOCH,
            NOW,
        )
        .expect("start initiator");
        let hello = initiator.hello().clone();
        let mut responder =
            ClassicResponder::new(responder_identity, initiator_identity.verifying_key())
                .expect("create responder");
        let accepted = responder
            .accept(&hello, ENDPOINT, EPOCH, NOW)
            .expect("accept hello");
        let initiator_session = derive_session_keys(
            initiator
                .finish(&accepted.accept, NOW)
                .expect("finish initiator"),
            None,
        )
        .expect("derive initiator keys");
        let responder_session =
            derive_session_keys(accepted.established, None).expect("derive responder keys");
        (initiator_session, responder_session)
    }

    fn fixed_tag() -> ConfirmationTag {
        compute_with_key(&FIXED_KEY, &FIXED_TRANSCRIPT)
    }

    #[test]
    fn hmac_sha256_matches_a_fixed_known_answer_vector() {
        assert_eq!(
            fixed_tag().as_bytes(),
            &[
                0xaa, 0x24, 0x28, 0xc7, 0x1c, 0x00, 0xa6, 0x27, 0x78, 0x2f, 0x90, 0x26, 0x94, 0xee,
                0xf4, 0x93, 0xbd, 0x64, 0x69, 0x0f, 0xbb, 0xbb, 0xba, 0x6c, 0xce, 0x32, 0x3a, 0x0b,
                0x94, 0xb2, 0x9d, 0xab,
            ]
        );
    }

    #[test]
    fn both_endpoints_agree_on_both_directional_confirmations() {
        let (initiator, responder) = established_session(0x11, 0x22);
        let transcript = initiator.identity.transcript_hash;

        for role in [ConfirmationRole::Initiator, ConfirmationRole::Responder] {
            let initiator_tag = compute_confirmation(&initiator.keys, role, &transcript);
            let responder_tag = compute_confirmation(&responder.keys, role, &transcript);
            assert_eq!(initiator_tag, responder_tag);
            verify_confirmation(&initiator.keys, role, &transcript, responder_tag.as_bytes())
                .expect("initiator verifies responder tag");
            verify_confirmation(&responder.keys, role, &transcript, initiator_tag.as_bytes())
                .expect("responder verifies initiator tag");
        }

        assert_ne!(
            compute_confirmation(&initiator.keys, ConfirmationRole::Initiator, &transcript),
            compute_confirmation(&initiator.keys, ConfirmationRole::Responder, &transcript)
        );
    }

    #[test]
    fn wrong_role_swapped_tag_and_wrong_transcript_fail_closed() {
        let (initiator, _) = established_session(0x11, 0x22);
        let transcript = initiator.identity.transcript_hash;
        let responder_tag =
            compute_confirmation(&initiator.keys, ConfirmationRole::Responder, &transcript);

        assert_eq!(
            verify_confirmation(
                &initiator.keys,
                ConfirmationRole::Initiator,
                &transcript,
                responder_tag.as_bytes(),
            ),
            Err(ConfirmationError::Mismatch)
        );
        assert_eq!(
            verify_confirmation(
                &initiator.keys,
                ConfirmationRole::Responder,
                &[0x67; TRANSCRIPT_HASH_LEN],
                responder_tag.as_bytes(),
            ),
            Err(ConfirmationError::Mismatch)
        );
    }

    #[test]
    fn truncated_oversized_and_bit_flipped_tags_fail_closed() {
        let (initiator, _) = established_session(0x11, 0x22);
        let transcript = initiator.identity.transcript_hash;
        let tag = compute_confirmation(&initiator.keys, ConfirmationRole::Initiator, &transcript);

        assert_eq!(
            verify_confirmation(
                &initiator.keys,
                ConfirmationRole::Initiator,
                &transcript,
                &tag.as_bytes()[..CONFIRMATION_LEN - 1],
            ),
            Err(ConfirmationError::InvalidLength {
                expected: CONFIRMATION_LEN,
                actual: CONFIRMATION_LEN - 1,
            })
        );

        let mut oversized = [0u8; CONFIRMATION_LEN + 1];
        oversized[..CONFIRMATION_LEN].copy_from_slice(tag.as_bytes());
        assert_eq!(
            verify_confirmation(
                &initiator.keys,
                ConfirmationRole::Initiator,
                &transcript,
                &oversized,
            ),
            Err(ConfirmationError::InvalidLength {
                expected: CONFIRMATION_LEN,
                actual: CONFIRMATION_LEN + 1,
            })
        );

        let mut changed = *tag.as_bytes();
        changed[17] ^= 1;
        assert_eq!(
            verify_confirmation(
                &initiator.keys,
                ConfirmationRole::Initiator,
                &transcript,
                &changed,
            ),
            Err(ConfirmationError::Mismatch)
        );
    }

    #[test]
    fn confirmation_from_a_different_key_schedule_fails_closed() {
        let (initiator, _) = established_session(0x11, 0x22);
        let (other, _) = established_session(0x33, 0x44);
        let transcript = initiator.identity.transcript_hash;
        let other_tag = compute_confirmation(&other.keys, ConfirmationRole::Initiator, &transcript);

        assert_eq!(
            verify_confirmation(
                &initiator.keys,
                ConfirmationRole::Initiator,
                &transcript,
                other_tag.as_bytes(),
            ),
            Err(ConfirmationError::Mismatch)
        );
    }

    #[test]
    fn tag_parser_rejects_noncanonical_lengths() {
        assert_eq!(
            ConfirmationTag::from_slice(&[0u8; CONFIRMATION_LEN - 1]),
            Err(ConfirmationError::InvalidLength {
                expected: CONFIRMATION_LEN,
                actual: CONFIRMATION_LEN - 1,
            })
        );
        assert!(ConfirmationTag::from_slice(&[0u8; CONFIRMATION_LEN]).is_ok());
    }
}
