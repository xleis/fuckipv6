//! Authenticated handshake-to-data-epoch bridge for the v2 classic profile.
//!
//! This module is the only supported path from [`DerivedSession`] keys to an
//! [`EpochSession`]. It verifies the peer's directional HMAC-SHA-256
//! confirmation before copying either data key into the AEAD state. Receiver
//! indices are supplied by the caller because they are local routing labels,
//! not key material, and are bound into every packet header and AAD.

use crate::confirmation::{
    verify_confirmation, ConfirmationError, ConfirmationRole, ConfirmationTag,
};
use crate::key_schedule::DerivedSession;
use crate::{Direction, EpochSession, ReceiveCipher, SendCipher, SessionError};
use std::time::Instant;
use thiserror::Error;
use zeroize::Zeroizing;

impl EpochSession {
    /// Verify a peer confirmation and install the handshake-derived keys.
    ///
    /// `local_role` is this endpoint's role, and `peer_confirmation` must be the
    /// tag generated by the opposite role. `local_receiver_index` is written by
    /// the peer into packets for this endpoint; `peer_receiver_index` is the
    /// index this endpoint writes into outgoing packets. The returned session is
    /// ready for bidirectional traffic under the same SID and epoch.
    pub fn from_handshake(
        derived: DerivedSession,
        local_role: ConfirmationRole,
        local_receiver_index: u32,
        peer_receiver_index: u32,
        peer_confirmation: &ConfirmationTag,
        now: Instant,
    ) -> Result<Self, HandshakeEpochError> {
        let DerivedSession { identity, mut keys } = derived;

        verify_confirmation(
            &keys,
            local_role.peer(),
            &identity.transcript_hash,
            peer_confirmation.as_bytes(),
        )
        .map_err(HandshakeEpochError::Confirmation)?;

        let (send_direction, receive_direction) = match local_role {
            ConfirmationRole::Initiator => (
                Direction::InitiatorToResponder,
                Direction::ResponderToInitiator,
            ),
            ConfirmationRole::Responder => (
                Direction::ResponderToInitiator,
                Direction::InitiatorToResponder,
            ),
        };

        let send_key = Zeroizing::new(*keys.data_key(send_direction));
        let receive_key = Zeroizing::new(*keys.data_key(receive_direction));
        let send = SendCipher::new(
            *send_key,
            identity.session_id,
            send_direction,
            identity.epoch,
            peer_receiver_index,
        );
        let receive = ReceiveCipher::new(
            *receive_key,
            identity.session_id,
            receive_direction,
            identity.epoch,
            local_receiver_index,
        );
        let session = Self::new(send, receive, now).map_err(HandshakeEpochError::Session)?;

        keys.erase();
        Ok(session)
    }
}

/// Errors returned while installing a handshake-derived data epoch.
#[derive(Debug, Error, Clone, Copy, PartialEq, Eq)]
pub enum HandshakeEpochError {
    /// The peer did not prove possession of the expected directional key.
    #[error("handshake key confirmation failed: {0}")]
    Confirmation(#[from] ConfirmationError),
    /// The resulting send/receive cipher pair was inconsistent.
    #[error("handshake epoch is invalid: {0}")]
    Session(#[from] SessionError),
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::confirmation::{compute_confirmation, ConfirmationRole};
    use crate::handshake::{ClassicInitiator, ClassicResponder, Ed25519Identity};
    use crate::key_schedule::derive_session_keys;
    use crate::transcript::{ENDPOINT_CONTEXT_HASH_LEN, SUITE_CHACHA20_POLY1305};

    const NOW: u64 = 1_700_000_000;
    const EPOCH: u16 = 7;
    const ENDPOINT: [u8; ENDPOINT_CONTEXT_HASH_LEN] = [0x5a; ENDPOINT_CONTEXT_HASH_LEN];
    const INITIATOR_RECEIVE_INDEX: u32 = 0xb1b2_c3d4;
    const RESPONDER_RECEIVE_INDEX: u32 = 0xa1a2_b3c4;

    fn expect_handshake_error(
        result: Result<EpochSession, HandshakeEpochError>,
        message: &str,
    ) -> HandshakeEpochError {
        match result {
            Ok(_) => panic!("{message}"),
            Err(error) => error,
        }
    }

    fn established_session() -> (DerivedSession, DerivedSession) {
        let initiator_identity = Ed25519Identity::from_seed([0x11; 32]);
        let responder_identity = Ed25519Identity::from_seed([0x22; 32]);
        let initiator = ClassicInitiator::start(
            &initiator_identity,
            responder_identity.verifying_key(),
            SUITE_CHACHA20_POLY1305,
            ENDPOINT,
            EPOCH,
            NOW,
        )
        .expect("start initiator");
        let hello = initiator.hello().clone();
        let mut responder =
            ClassicResponder::new(responder_identity, initiator_identity.verifying_key())
                .expect("create responder");
        let accepted = responder
            .accept(&hello, ENDPOINT, EPOCH, NOW)
            .expect("accept hello");
        let initiator_session = derive_session_keys(
            initiator
                .finish(&accepted.accept, NOW)
                .expect("finish initiator"),
            None,
        )
        .expect("derive initiator keys");
        let responder_session =
            derive_session_keys(accepted.established, None).expect("derive responder keys");
        (initiator_session, responder_session)
    }

    #[test]
    fn authenticated_endpoints_exchange_packets_both_directions() {
        let (initiator, responder) = established_session();
        let sid = initiator.identity.session_id;
        let transcript = initiator.identity.transcript_hash;
        let initiator_confirmation =
            compute_confirmation(&initiator.keys, ConfirmationRole::Initiator, &transcript);
        let responder_confirmation =
            compute_confirmation(&responder.keys, ConfirmationRole::Responder, &transcript);
        let now = Instant::now();

        let mut initiator = EpochSession::from_handshake(
            initiator,
            ConfirmationRole::Initiator,
            INITIATOR_RECEIVE_INDEX,
            RESPONDER_RECEIVE_INDEX,
            &responder_confirmation,
            now,
        )
        .expect("install initiator epoch");
        let mut responder = EpochSession::from_handshake(
            responder,
            ConfirmationRole::Responder,
            RESPONDER_RECEIVE_INDEX,
            INITIATOR_RECEIVE_INDEX,
            &initiator_confirmation,
            now,
        )
        .expect("install responder epoch");

        assert_eq!(initiator.session_id(), sid);
        assert_eq!(responder.session_id(), sid);
        assert_eq!(initiator.epoch(), EPOCH);
        assert_eq!(responder.epoch(), EPOCH);

        let mut request = [0u8; 128];
        let request_len = initiator
            .seal(b"authenticated request", &mut request, now)
            .expect("seal request");
        assert_eq!(
            responder
                .open_in_place(&mut request[..request_len], now)
                .expect("open request"),
            b"authenticated request"
        );

        let mut response = [0u8; 128];
        let response_len = responder
            .seal(b"authenticated response", &mut response, now)
            .expect("seal response");
        assert_eq!(
            initiator
                .open_in_place(&mut response[..response_len], now)
                .expect("open response"),
            b"authenticated response"
        );
    }

    #[test]
    fn wrong_role_or_confirmation_prevents_key_installation() {
        let (initiator, responder) = established_session();
        let transcript = initiator.identity.transcript_hash;
        let initiator_confirmation =
            compute_confirmation(&initiator.keys, ConfirmationRole::Initiator, &transcript);
        let responder_confirmation =
            compute_confirmation(&responder.keys, ConfirmationRole::Responder, &transcript);

        let err = expect_handshake_error(
            EpochSession::from_handshake(
                initiator,
                ConfirmationRole::Initiator,
                INITIATOR_RECEIVE_INDEX,
                RESPONDER_RECEIVE_INDEX,
                &initiator_confirmation,
                Instant::now(),
            ),
            "initiator must not accept its own confirmation",
        );
        assert_eq!(
            err,
            HandshakeEpochError::Confirmation(ConfirmationError::Mismatch)
        );

        let mut wrong_bits = *responder_confirmation.as_bytes();
        wrong_bits[0] ^= 1;
        let wrong_confirmation = ConfirmationTag::from_slice(&wrong_bits).expect("32-byte tag");
        let err = expect_handshake_error(
            EpochSession::from_handshake(
                responder,
                ConfirmationRole::Responder,
                RESPONDER_RECEIVE_INDEX,
                INITIATOR_RECEIVE_INDEX,
                &wrong_confirmation,
                Instant::now(),
            ),
            "tampered confirmation must fail",
        );
        assert_eq!(
            err,
            HandshakeEpochError::Confirmation(ConfirmationError::Mismatch)
        );
    }

    #[test]
    fn a_different_transcript_cannot_authorize_installation() {
        let (initiator, _responder) = established_session();
        let (other, _) = established_session();
        let other_transcript = other.identity.transcript_hash;
        let other_confirmation =
            compute_confirmation(&other.keys, ConfirmationRole::Responder, &other_transcript);

        let err = expect_handshake_error(
            EpochSession::from_handshake(
                initiator,
                ConfirmationRole::Initiator,
                INITIATOR_RECEIVE_INDEX,
                RESPONDER_RECEIVE_INDEX,
                &other_confirmation,
                Instant::now(),
            ),
            "confirmation from another transcript must fail",
        );
        assert_eq!(
            err,
            HandshakeEpochError::Confirmation(ConfirmationError::Mismatch)
        );
    }
}
